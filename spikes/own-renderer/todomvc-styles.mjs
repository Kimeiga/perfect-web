// TodoMVC's two drawings of a todo's checkbox, served from this origin
// (track `todomvc`, W7; run by todomvc.sh).
//
// The official stylesheet (`todomvc-app-css`, CC BY 4.0, Sindre Sorhus) draws
// a todo's checkbox, a circle and a ticked circle, as `data:` images in two
// rules. A page's generated policy allows images of its own origin only
// (`img-src 'self'`, ADR-0333), so the sheet is shown without them. This
// reads the two drawings out of the sheet, as it ships, writes each as an
// SVG file, and writes this app's own sheet, loaded after the official one
// as TodoMVC's spec allows ("if you need to change some styles, use the
// app.css file"): the same two rules, pointing at the files. Nothing here is
// drawn by hand, so the drawings are the official ones, and a sheet that
// stopped carrying them fails this script rather than shipping a page
// without its checkboxes.
//
// usage: node todomvc-styles.mjs <todomvc-app-css/index.css> <out directory>

import { readFileSync, writeFileSync } from "node:fs";

const [css, out] = process.argv.slice(2);
const sheet = readFileSync(css, "utf8");

/** The drawing the rule headed `selector` gives its background. */
function drawing(selector) {
  const rule = sheet
    .split("}")
    .find((r) => r.replace(/\s+/g, " ").trimStart().startsWith(`${selector} {`));
  const uri = /url\('data:image\/svg\+xml;utf8,([^']*)'\)/.exec(rule ?? "");
  if (!uri) throw new Error(`the official sheet draws no checkbox for ${selector}`);
  return decodeURIComponent(uri[1]);
}

writeFileSync(`${out}/todomvc-circle.svg`, `${drawing(".todo-list li .toggle + label")}\n`);
writeFileSync(
  `${out}/todomvc-checked.svg`,
  `${drawing(".todo-list li .toggle:checked + label")}\n`,
);
writeFileSync(
  `${out}/todomvc-pleris.css`,
  [
    "/* This app's own sheet, after TodoMVC's (todomvc-app.css, CC BY 4.0, Sindre Sorhus):",
    "   the same two drawings of a todo's checkbox, served from this origin, since a",
    "   page's policy refuses a data: image. Generated by todomvc-styles.mjs from that",
    "   sheet. */",
    ".todo-list li .toggle + label {",
    "\tbackground-image: url('/todomvc-circle.svg');",
    "}",
    "",
    ".todo-list li .toggle:checked + label {",
    "\tbackground-image: url('/todomvc-checked.svg');",
    "}",
    "",
  ].join("\n"),
);
